    <h1>In Praise of Doubt</h1>
    <p>by Bertolt Brecht</p>

    <p>
        Bertolt Brecht was a few things, notably a German communist dramatist
        during the time of the Nazis rise to power. He's probably most famous
        for 'The Threepenny Opera' or 'Die Dreigoschenoper' which is a play with
        music depicting a socialist critique of the poverty of the capitalist
        world; I first heard of it due to a reference to 'Pirate Jenny' in
        another song who's a character in the play but I haven't actually seen
        the play - maybe I should watch it sometime. However Brecht was also a
        poet and while browsing in the library I found a book collecting all his
        poetry.
    </p>
    <p>
        The only poem I had seen previously from Brecht was a short one written
        about his disillusionment with the East German government called 'The
        Solution'. In this book there were other interesting poems that I
        enjoyed; the one I want to focus on here is investigating the role of
        doubt in the world. I also want to try something a little more detailed
        where I go over the poem bit by bit despite not really being a great
        poetry critic; just going over my interpretation of it. Note that this
        is a translation from German so perhaps I should read the original as
        well to get a feel for the exact lingo.
    </p>

    <h2>In Praise of Doubt</h2>
    <pre>
        Praised be doubt! I advise you to greet
        Cheerfully and with respect the man
        Who tests your word like a bad penny.
        I'd like you to be wise and not to give
        Your word with too much assurance.</pre>
    <p>
        Here the poem is laying out the stakes, immediately being
        enthusiastically in favour of doubting things you hear. Bad penny here
        is a reference to counterfeit money such that you shouldn't dislike
        people who question what you say.
    </p>
    <pre>
        Read history and see
        The headlong flight of invincible armies.
        Wherever you look
        Impregnable strongholds collapse and
        Even if the Armada was innumerable as it left port
        The returning ships
        Could be numbered.</pre>
    <p>
        This part I really appreciate - so often I see people asserting things
        or predicting the future confidently without a shred of introspection
        and it's extremely off-putting to me but it appears like those kinds of
        things are rewarded. That's not to say you shouldn't believe in things
        whole-heartedly but blind faith is how you get stuck in a cult. I guess
        the Titanic wasn't as prominent as the premier example of an unsinkable
        ship back then so perhaps that's more modern thinking.
    </p>
    <pre>
        Thus one day a man stood on the unattainable summit
        And a ship reached the end of
        The endless sea.</pre>
    <p>
        Here we see a bit of metaphor to show the absurdity of stating absolutes
        and certainties in many cases, I love the poetic flow of this stanza.
    </p>
    <pre>
        O beautiful the shaking of heads
        Over the indisputable truth!
        O brave the doctor's cure
        Of the incurable patient!</pre>
    <p>
        Similar to the previous stanza about the revocation of certainties. As
        an atheist Brecht is probably evoking religious doctrine with the
        'indisputable truth' section; since religious people tend to have
        eternal truths where questioning them is a dangerous affair.
    </p>
    <pre>
        But the most beautiful of all doubts
        Is when the downtrodden and despondent raise their heads
                and
        Stop believing in the strength
        Of their oppressors.</pre>
    <p>
        Now we turn to a more political stance about questioning the ruling
        classes' authority over the people.
    </p>
    <pre>
        Oh, how laboriously the new truth was fought for!
        What sacrifices it cost!
        How difficult it was to see
        That things were thus and not thus!
        What a sigh of relief one day a man entered it in the record of
                knowledge.
        For a long time perhaps it stands there, and many generations
        Live with it and regard it as eternal wisdom
        And the learned scorn all who are ignorant of it.
        And then it may happen that a suspicion arises, for new experience
        Makes the established truth open to question. Doubt spreads
        And then one day a man thoughtfully strikes it out
        From the record of knowledge.</pre>
    <p>
        Pondering about what is common knowledge and how it changes. It is
        strange to think as a parallel to this the 'natural' state of humanity
        throughout history and how malleable we are. People lived under the yoke
        of kings, barons and lords for hundreds of years as serfs in villages.
        Poeple suffered as slaves and fought as soldiers against one another.
        Nowadays we still have similar constructs but in a different form; power
        is acquired and dispersed in ways that would seem unusual to our
        forebears but will surely be seen as absurd to our descendents. I assume
        this is what Brecht had in mind given his Marxist tendencies - about how
        the contradictions force the state of the world to be re-evaluated as it
        is found wanting.
    </p>
    <pre>
        Deafened by commands, examined
        For his fitness to fight by bearded doctors, inspected
        By resplendent creatures with golden insignia, admonished
        By solemn clerics who throw at him a book written by God
                himself
        Instructed
        By impatient schoolmaster, stands the poor man and is told
        That the world is the best of worlds and that the hole
        In the roof of his hovel was planned by God in person.
        Truly he finds it hard
        To doubt this world.</pre>
    <p>
        This one is sarcastically striking at religious gospel and its lofty
        ideals failing to address the hardships of the real world. It reminds me
        of Joe Hill, who was an American songwriter, and wrote a song called
        'The Preacher and the Slave' about the preachings of the Salvation Army
        and how they didn't help people in there here and now but promising
        glory after death. It's actually where the phrase 'pie in the sky' comes
        from.<Footnote
            >Source: <a href="https://en.wiktionary.org/wiki/pie_in_the_sky"
                >https://en.wiktionary.org/wiki/pie_in_the_sky</a
            ></Footnote
        >
    </p>
    <pre>
        The thoughtless who never doubt
        Meet the thoughtful who never act.
        They doubt, not in order to come to a decision but
        To avoid a decision. Their heads
        They use only for shaking. With anxious faces
        They warn the crews of sinking ships that water is dangerous.
        Beneath the murderer's axe
        They ask themselves if he isn't human too.
        Murmuring something
        About the situation not yet being clarified, they go to bed.
        Their only action is to vacillate.
        Their favourite phrase is: not yet ripe for discussion.</pre>
    <p>
        Ouch, this feels like a personal excoriation of me. I am indecisive and
        have a tendency to be paralysed by it into taking what appears to be the
        default option, or the option of least resistance. This causes outcomes
        which are worse than taking any other option sometimes and leads to a
        lack of deliberacy/agency in the way I feel about my situation. In a
        political sense this would be about people and leaders who refuse to
        make difficult decisions and end up kicking the can down the road. It's
        interesting in the poetry craft how the first two lines are used to
        transition and help the reader with the change in direction. It also
        cautions against doubt when it's overbearing. For Brecht this may have
        been the leaders of political parties or groups that allow them to
        stagnate and fall behind with the times - especially pressing in Germany
        at the time.
    </p>
    <pre>
        Therefore, if you praise doubt
        Do not praise
        The doubt which is a form of despair.</pre>
    <p>
        This is a short addendum to the previous stanza but it really resonates
        politically currently. It feels heavily like people often want to avoid
        looking at problems holistically and the tinkering around the edges is
        insufficient to address the challenges of today. This may sound vague so
        more specifically around things like wealth consolidation, climate
        change, ownership of land and public resources and tech control/monopoly
        feel like they're slowly deteriorating and little adjustments to
        ameliorate these things do nothing to address the underlying causes and
        general slide.
    </p>
    <pre>
        What use is the ability to doubt to a man
        Who can't make up his mind?
        He who is content with too few reasons
        May act wrongly
        But he who needs too many
        Remains inactive under danger.</pre>
    <p>
        As we approach the crux of the poem and come to the core thesis we get
        to a message of having a healthy amount of doubt: enough to avoid
        dogmatic thinking but not so much to be too lethargic and indecisive.
        Seems like a pretty dull message but everything seems more interesting
        when it's written poetically.
    </p>
    <pre>
        You who are a leader of men, do not forget
        That you are that because you doubted other leaders.
        So allow the led
        Their right to doubt.</pre>
    <p>
        This is the end of the poem and it ends with a key theme throughout
        Brecht's work: questioning core structures. I like that it ends
        positively of doubt; perhaps there was some meta analysis going on where
        to be doubtful properly you must doubt doubt itself. Here it's an
        explicit message to the leaders of communities, parties and countries to
        allow freedom of expression and to permit dissent which is a good
        message in my opinion.
    </p>

    <p>
        To sum up, I really enjoy the flow and style of this poem and the
        message is something that really resonates with me. I hope if you read
        this you enjoyed it too; I'm not sure about the style of review in this
        post but it was interesting to do. Remember to keep doubting, stay
        sceptical.
    </p>
